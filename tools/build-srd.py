#!/usr/bin/env python3
"""Build data/srd.js from the 5e-bits SRD database (D&D 5e SRD 5.1, CC-BY-4.0).

Usage: python3 tools/build-srd.py <dir containing 5e-SRD-*.json>
Source: https://github.com/5e-bits/5e-database/tree/main/src/2014/en
"""
import json, sys, os

src = sys.argv[1]
load = lambda n: json.load(open(os.path.join(src, f"5e-SRD-{n}.json")))

classes = {}
for c in load("Classes"):
    classes[c["index"]] = {
        "name": c["name"],
        "hitDie": c["hit_die"],
        "saves": [s["index"] for s in c["saving_throws"]],
        "castAbility": (c.get("spellcasting") or {}).get("spellcasting_ability", {}).get("index"),
        "subclasses": [s["name"] for s in c.get("subclasses", [])],
        "slots": {},      # level -> [slots for spell levels 1..9]
        "cantrips": {},   # level -> cantrips known
        "known": {},      # level -> spells known (for known-casters)
    }

for lv in load("Levels"):
    if lv.get("subclass"):
        continue
    c = classes[lv["class"]["index"]]
    sc = lv.get("spellcasting")
    if not sc:
        continue
    n = lv["level"]
    c["slots"][n] = [sc.get(f"spell_slots_level_{i}", 0) for i in range(1, 10)]
    if "cantrips_known" in sc:
        c["cantrips"][n] = sc["cantrips_known"]
    if "spells_known" in sc:
        c["known"][n] = sc["spells_known"]

spells = []
for s in load("Spells"):
    spells.append({
        "n": s["name"],
        "l": s["level"],
        "s": s["school"]["name"],
        "t": s["casting_time"],
        "r": s["range"],
        "c": "".join(s["components"]) + (f" ({s['material']})" if s.get("material") else ""),
        "d": s["duration"],
        "conc": s.get("concentration", False),
        "rit": s.get("ritual", False),
        "cl": [c["index"] for c in s.get("classes", [])],
        "desc": "\n\n".join(s.get("desc", [])),
        "hl": "\n\n".join(s.get("higher_level", [])),
    })
spells.sort(key=lambda x: (x["l"], x["n"]))

out = ("// Generated by tools/build-srd.py from the D&D 5e SRD 5.1 (CC-BY-4.0, Wizards of the Coast)\n"
       "// via https://github.com/5e-bits/5e-database. Do not edit by hand.\n"
       "window.SRD = " + json.dumps({"classes": classes, "spells": spells}, separators=(",", ":")) + ";\n")
open(os.path.join(os.path.dirname(__file__), "..", "data", "srd.js"), "w").write(out)
print(f"{len(classes)} classes, {len(spells)} spells, {len(out)//1024} KB")
